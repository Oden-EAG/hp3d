!     EVALUATION BY FROBENIUS METHOD
!
!----------------------------------------------------------------------
!       compute factorial coefficients for Bessel-Frobenius series
        function Rfact(N) result(F)      
          use iso_fortran_env, wp => real64   
          implicit none
          integer, intent(in) :: N
          real(8) :: F
          integer :: j
  !
          if (N.lt.0) then
           write(*,*) 'Rfact: N = ',N
           stop 1
          endif
  !
          F=1._wp
          if (N.eq.0) return
          do j=1,N
           F = F*2._wp/j
          enddo
!
        end function
